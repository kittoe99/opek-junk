/** Shared by the catalog and estimate summary; labels live on the parent controls. */
export const ItemIconRenderer = ({ imagePath, className = '', size = 24 }: IconProps & { imagePath: string }) => {
  const iconKey = imagePath.replace('/items/', '').replace('.svg', '');
  const IconComponent = JunkIconMap[iconKey];
  if (IconComponent) {
    return <IconComponent className={`junk-item-illustration ${className}`} size={size} />;
  }
  return <img src={imagePath} alt="" className={className} style={{ width: size, height: size }} />;
};
